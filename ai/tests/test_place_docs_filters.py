"""KB-5 수집 필터 — 그 문서가 **그 장소** 얘기인가.

상호명 정확 일치만으로는 표제어가 애초에 장소가 아닌 경우를 못 거른다. 두 필터가
실측 2,053건에서 588건(28.6%)을 쳐냈다. 틀린 설명이 후보에 붙는 것은 설명이 없는
것보다 나쁘다 — 모델이 그걸 읽고 근거로 쓴다.
"""

from __future__ import annotations

import pytest

from trippilot.poi_curation.place_docs import is_disambiguation, mentions_region


# ── 지역 교차검증 ──────────────────────────────────────────────────────

# 실제로 잡힌 오매칭 (수집 배치에서 그대로 가져온 것)
_실제_오매칭 = [
    ("전파를 사용하여 물체의 거리를 결정하는 시스템이다.", "서울", "서울특별시 성동구"),
    ("방시혁이 2005년 설립한 대한민국의 엔터테인먼트 기업이다.", "서울", "서울특별시 용산구"),
    ("중화민국의 군인 리원(1905~1977)은 …", "부산", "부산광역시 중구"),
]


@pytest.mark.parametrize("text,region,address", _실제_오매칭)
def test_다른_주제의_동명_문서는_지역을_안_적는다(text, region, address) -> None:
    """장소를 설명하는 백과 문서는 거의 항상 소재지를 적고, 인물·작품·개념은 안 적는다."""
    assert mentions_region(text, region, address) is False


def test_소재지를_적은_문서는_통과한다() -> None:
    assert mentions_region(
        "계양산(桂陽山)은 인천광역시 계양구에 있는 높이 395 m의 산이다.",
        "인천", "인천광역시 계양구 계산동",
    )


def test_행정단위_접미사가_달라도_걸린다() -> None:
    """주소는 '제주시'인데 본문은 '제주'라고만 쓰는 일이 흔하다."""
    assert mentions_region("제주 동문시장은 …", "제주시", "제주특별자치도 제주시 이도1동")


def test_검증할_지역이_없으면_버린다() -> None:
    """모르면 통과가 아니라 기각이다 — 빈 것이 틀린 것보다 낫다."""
    assert mentions_region("어떤 설명 문장이다.", "", "") is False


# ── 동음이의어 ────────────────────────────────────────────────────────


def test_동음이의어_문서는_지역_필터를_통과해도_걸러진다() -> None:
    """나열된 지역 중 하나가 맞는 지역이라 `mentions_region` 은 참이 된다.

    그래서 필터가 **둘 다** 필요하다 — 이 한 건이 그 이유다.
    """
    text = ("녹동서원은 다음을 가리키는 말이다. 녹동서원(鹿洞書院) - 대구광역시 달성군 "
            "가창면 우록리 585-1 녹동서원(鹿洞書院 ) - 전라남도 영암군 영암읍 교동리 356")
    assert mentions_region(text, "대구", "대구광역시 달성군")  # 지역 필터는 통과한다
    assert is_disambiguation(text)  # 이쪽이 잡는다


@pytest.mark.parametrize("text", [
    "녹동서원은 다음을 가리키는 말이다. …",
    "청계산의 다른 뜻은 다음과 같다. …",
    "갑사에는 다음과 같은 뜻이 있다. …",
])
def test_동음이의어_어법_변종(text) -> None:
    assert is_disambiguation(text)


def test_본문_중간의_다음과_같이는_정상_문장이다() -> None:
    """첫머리만 보는 이유 — 설명문 안의 "다음과 같"을 동음이의어로 읽으면 안 된다."""
    text = ("수원 화성은 경기도 수원시에 있는 조선시대 성곽이다. 축성에 쓰인 기술은 "
            "다음과 같은 점에서 당대 최고 수준이었다. 거중기와 녹로를 …")
    assert is_disambiguation(text) is False
