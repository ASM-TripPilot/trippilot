"""테마 태그(`혼밥`·`뷰`…)와 사용자 말 사이의 동의어 표 (TRIP-1537).

장소에 붙은 테마 태그는 방문자 투표 키워드에서 뽑은 13종이다. 사용자는 "혼자 가기 좋은 곳"·"아이랑"·"사진 찍기 좋은" 처럼
말하므로 태그 글자와 안 맞는다 — 이 표가 말 → 태그를 잇는다. 결정론(정규식)이고 LLM 을 부르지 않는다.

짧은 낱말이 다른 말에 박히는 오탐(`아이스크림`·`오래된`·`싼`)을 피하려고 **뜻이 분명한 구절만** 싣는다.
"""

from __future__ import annotations

import re

# 테마 태그 13종 — 데이터 쪽 어휘와 같아야 한다(정제 어휘표). 순서는 결과 순서다.
THEME_TAGS: tuple[str, ...] = (
    "혼밥", "혼술", "단체", "데이트", "뷰", "야외", "사진", "아이동반", "작업", "분위기", "가성비", "주차", "오래머물기",
)

_PHRASES: dict[str, str] = {
    "혼밥": r"혼밥|혼자\s*(서\s*)?(밥|식사|먹)|혼자\s*(서\s*)?(가기|가도|가볼|가 볼|가는|오기|즐기)|1인",
    "혼술": r"혼술|혼자\s*(서\s*)?(술|한잔|한 잔|마시)|혼자\s*(서\s*)?(가기|가도|가볼|가 볼|가는|오기|즐기)",
    "단체": r"단체|모임|회식|동호회|여럿|대인원|\d+\s*명",
    "데이트": r"데이트|연인|커플|애인|기념일|프러포즈|소개팅|대화하기",
    "뷰": r"뷰|전망|경치|풍경|조망|바다\s*(가\s*)?보이|강\s*(이\s*)?보이|산\s*(이\s*)?보이",
    "야외": r"야외|테라스|루프탑|정원|마당",
    "사진": r"사진|인스타|포토|인생샷|감성샷",
    "아이동반": r"아이(랑|와|들|가|도)|아이\s*(데리|동반)|아기|애기|어린이|유아|키즈|애들|가족",
    "작업": r"작업|공부|노트북|카공|스터디|과제|재택|집중",
    "분위기": r"분위기|감성|아늑|조용|차분|인테리어|컨셉|힙한|무드",
    "가성비": r"가성비|저렴|합리적|알뜰|착한\s*가격|싸고",
    "주차": r"주차|차\s*(를\s*)?(가져|끌고|몰고)|자차|운전",
    "오래머물기": r"오래\s*(머물|앉|있)|느긋|여유(롭|있게)|수다|쉬엄",
}
_COMPILED = {tag: re.compile(p) for tag, p in _PHRASES.items()}


def themes_in(text: str | None) -> tuple[str, ...]:
    """말에 든 테마 태그. 없으면 빈 튜플 — `THEME_TAGS` 순서로 돌려준다."""
    if not text:
        return ()
    return tuple(tag for tag in THEME_TAGS if _COMPILED[tag].search(text))
