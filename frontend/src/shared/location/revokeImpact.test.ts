import { revokeImpact } from './revokeImpact';

/**
 * TRIP-609 · BR-U6-30 — 철회 영향 고지 문안 순수 조립(다이얼로그·default 배너 공통 소비처).
 *
 * 무엇을 보장하나: 위치 동의 철회가 **무엇을 멈추고 무엇을 계속하는지**를 한 곳에서 조립한다.
 * 중단 3(이동 지연 알림·실시간 Plan-B 재계획·현 위치 기반 추천)과 계속 2(예정 일정 알림·날씨/휴무
 * 트리거)를 정확한 개수·순서로 낸다. 이 한 함수를 철회 다이얼로그(중단3+계속2 구조화 리스트, Q1 확정)
 * 와 default "꺼도 계속 동작해요" 배너(계속2)가 함께 소비해 문구 중복을 없앤다(deletionScope 단일
 * 소유와 동형).
 *
 * 왜 이 문자열이 여기서 못 박히나: 사용자 가시 문안이고 BR-U6-30 의 법적/동의 고지라, 자구가 곧
 * 계약이다 — test-designer 가 BR-U6-30 에 충실하게 확정하고 구현자는 이 값을 그대로 산출한다.
 *
 * (개념) 순수 함수라 같은 호출이면 항상 같은 결과 — 마지막 케이스가 그 성질을 잰다. 매처
 * `toEqual` = 배열의 순서·값까지 깊은 동등(개수·순서를 함께 잠근다).
 */
describe('TRIP-609 · revokeImpact (BR-U6-30)', () => {
  it('중단 항목을 정확히 3개, 정본 순서로 낸다', () => {
    expect(revokeImpact().stops).toEqual([
      '이동 지연 알림',
      '실시간 Plan-B 재계획',
      '현 위치 기반 추천',
    ]);
  });

  it('계속 항목을 정확히 2개, 정본 순서로 낸다(철회 후에도 동작 = INV-4 침묵 금지)', () => {
    expect(revokeImpact().continues).toEqual([
      '예정 일정 알림',
      '날씨·휴무 트리거',
    ]);
  });

  it('순수 함수 — 같은 호출이 항상 같은 결과를 낸다', () => {
    expect(revokeImpact()).toEqual(revokeImpact());
  });
});
