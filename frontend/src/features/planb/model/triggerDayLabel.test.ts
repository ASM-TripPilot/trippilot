import { triggerDayLabel } from './triggerDayLabel';

/**
 * 상황 감지 FE-B · frontend-components §3.4 — 트리거 날짜를 표시 시점에 상대어로 바꾼다(BR-SA-12 ②).
 *
 * 무엇을 보장하나:
 *  - 같은 날이면 **null**(알약·시트에 날짜어를 붙이지 않는다 — 오늘 일은 옛 출력 그대로).
 *  - 다음 날이면 `내일` — 월말·연말·윤일을 넘겨도 같다.
 *  - 그 밖(모레 이후·지난 날)은 `M월 D일`(앞자리 0 없음). 상대어는 '내일' 하나뿐이다(모레 금지).
 *  - 'YYYY-MM-DD' 꼴이 아니면 null — 모르는 날짜를 지어내지 않는다.
 *
 * 성질(전 날짜에서 다음 날은 '내일')은 `triggerLabel.property.test.ts`(PBT-SA-22)가 본다.
 * 3동작: 준비(트리거 날짜·오늘) → 실행(triggerDayLabel) → 단언(문자열 완전 일치·null).
 */

describe('triggerDayLabel — 표시 시점 날짜어', () => {
  it('D1 같은 날이면 null 이다', () => {
    expect(triggerDayLabel('2026-10-19', '2026-10-19')).toBeNull();
  });

  it.each([
    ['평일', '2026-10-19', '2026-10-20'],
    ['월말', '2026-10-31', '2026-11-01'],
    ['연말', '2026-12-31', '2027-01-01'],
    ['평년 2월 말', '2026-02-28', '2026-03-01'],
    ['윤년 2월 28일', '2028-02-28', '2028-02-29'],
    ['윤일', '2028-02-29', '2028-03-01'],
  ])('D2 %s — 오늘 %s 의 다음 날 %s 는 "내일"', (_name, today, tomorrow) => {
    expect(triggerDayLabel(tomorrow, today)).toBe('내일');
  });

  it.each([
    ['모레', '2026-10-21', '10월 21일'],
    ['다음 달 한 자리 날', '2026-11-05', '11월 5일'],
    ['지난 날', '2026-10-18', '10월 18일'],
    ['다음 해', '2027-01-09', '1월 9일'],
  ])('D3 %s(%s)는 "%s" — 앞자리 0 없는 M월 D일', (_name, date, expected) => {
    expect(triggerDayLabel(date, '2026-10-19')).toBe(expected);
  });

  it.each([[''], ['2026-10-2'], ['20261020'], ['내일']])(
    'D4 날짜 꼴이 아닌 "%s" 는 null 이다',
    (date) => {
      expect(triggerDayLabel(date, '2026-10-19')).toBeNull();
    }
  );
});
