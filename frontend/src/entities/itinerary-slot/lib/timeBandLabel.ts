/**
 * TRIP-295 · BR-U3-07 · PBT-U3-2 (01b D5) — 슬롯 시작 시각(`HH:mm:ss`) → 시간대 라벨 4종.
 *
 * 초안 화면(h11·h17)은 검증 시각을 그대로 내지 않고 이 라벨만 낸다. 반환 타입이 `string`이
 * 아니라 리터럴 유니온이라 "네 값 중 하나"를 tsc가 테스트보다 먼저 지킨다 — 네 리터럴 밖의
 * 문자열이 여기서 나갈 길이 없다(INV-3 · BR-U3-08). 성격 축(`활동`·`식사` 등) 합성은 매핑
 * 정본이 없어 이 함수의 범위 밖이다(01b D3).
 *
 * 왜 이 형태인가: 네 구간의 경계가 전부 정시(05·11·14·17)이고 `HH:mm:ss`는 자리수가 고정된
 * 0채움 문자열이라 **사전순 비교가 곧 시간 순서**다. 그래서 동결 경계표의 값을 그대로 적어
 * 놓고 위에서부터 걸러낸다 — 표의 한 줄이 코드 한 줄이라 코드와 표를 눈으로 대조할 수 있다.
 * 0채움이 아닌 문자열(`'9:00:00'`)은 이 전제 밖이다: 형식은 서버가 보증한다(INV-2 검증값).
 *
 * 함정: 저녁만 `17:00:00~23:59:59`와 `00:00:00~04:59:59` 두 조각(자정 랩어라운드)이라
 * `시작 <= t && t <= 끝` 한 줄로 판정되지 않는다. 첫 줄과 마지막 줄이 같은 라벨을 내는
 * 이 비대칭이 그 조각이다. 시계는 읽지 않는다 — 인자 문자열이 입력의 전부다.
 */
export type TimeBandLabel = '오전' | '점심' | '오후' | '저녁';

export function timeBandLabel(startAt: string): TimeBandLabel {
  if (startAt < '05:00:00') return '저녁';
  if (startAt < '11:00:00') return '오전';
  if (startAt < '14:00:00') return '점심';
  if (startAt < '17:00:00') return '오후';
  return '저녁';
}
