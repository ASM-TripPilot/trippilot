--
-- ## 왜 지금 데이터를 마이그레이션으로 넣나
--
-- 폐업한 가게가 `ACTIVE` 로 남아 있으면 **후보 풀에 올라가 일정에 배치된다.** 가장 오래된 것은
-- 2013-05-23 폐업이다 — 10년 넘게 문 닫은 가게를 사용자에게 추천하고 있었다는 뜻이다.
--
-- 판정은 AI 팀이 했다(LOCALDATA 지방행정 인허가 대조, `ai/data/poi_business_status.json`).
-- 주소 4요소 키 + 상호 일치만 매칭했고 **주소가 같아도 상호가 다르면 제외**했다(965건) —
-- 같은 건물의 다른 가게를 폐업 처리하는 쪽이 훨씬 되돌리기 어려운 오류이기 때문이다.
--
-- ## 왜 API 가 아니라 마이그레이션인가
--
-- 반복 수신 경로(`POST /internal/pois/business-status`)를 제안했다가 **접었다.** 신규 유입
-- 폐업분은 AI 수집 게이트가 이미 막고(PR #475), 남은 것은 **기존 등록분 한 배치**다.
-- 호출자가 없는 표면을 먼저 만들면 그게 곧 죽은 계약이 된다.
--
-- 다만 "오늘 등록된 POI 가 내년에 폐업하는 것"은 게이트가 못 막는다 — 그때 두 번째 배치가
-- 오면 **재발을 보고** 수신 경로를 만든다. 지금은 이 파일 하나가 최소다.
--
-- ## 범위를 source 로 좁히는 이유
--
-- 조인 키는 TourAPI `content_id` 다. `source` 를 안 걸면 같은 숫자를 `source_ref` 로 쓰는
-- 다른 벤더 수집분이 **엉뚱하게 폐업 처리**된다. `(source, source_ref)` 는 V2.23 의 부분 유니크
-- 인덱스라 이 조합으로 최대 1행이다.
--
-- ## 확정 일정은 흔들리지 않는다
--
-- 확정 시 동결된 `poi_snapshot` 은 별도 테이블이라 그대로다(INV-U1-03). 이미 확정한 여행은
-- 폐업 처리 뒤에도 그 장소를 그대로 보여준다 — 바뀌는 것은 **앞으로의 후보 풀**뿐이다.
