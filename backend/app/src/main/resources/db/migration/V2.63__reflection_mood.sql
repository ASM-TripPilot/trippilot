-- V2.63 회고의 기분·한 줄 메모 (TRIP-828 중 mood·shortMemo 몫)
--
-- 오늘의 회고 화면(j03)이 그날의 기분과 한 줄 메모를 받는데 **저장할 자리가 없었다.** 프론트는
-- "다시 들어오면 사라지는 입력"이라 그 입력을 화면에서 아예 빼 두고 있었다.
--
-- **U5 정본(§4.1)에는 없는 컬럼이다** — 화면이 먼저 요구한 것이라 정본보다 이쪽이 앞선다.
--
-- 둘 다 NULL 허용 = 남기지 않음. 카드와 별개의 사용자 입력이라 INV-U5-07("비어 있을 수 없다") 밖이다.
-- 기존 행은 NULL 이라 백필이 없다.
--
-- mood 에 CHECK 를 걸지 않는다: 값 집합의 정본은 화면(Figma)이고 백엔드는 그것을 못 본다. 애플리케이션이
-- 코드 모양(영문·숫자·밑줄·하이픈)만 받는다. 집합이 굳으면 그때 CHECK 를 건다 — source 컬럼과 같은 판단.
--
-- short_memo 의 60 은 화면 상한이다. varchar(n) 은 문자 수를 세므로 한글·이모지도 60자다.
ALTER TABLE reflection
  ADD COLUMN mood       varchar(20),
  ADD COLUMN short_memo varchar(60);
