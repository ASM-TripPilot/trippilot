-- V2.62 trip 일과 창 (TRIP-1252 후속 · 실사용 피드백 2026-10-07 "일정을 무조건 9시부터 짜준다")
--
-- 지금까지 하루 창은 코드 상수 09:00~21:00 이었고 사용자가 말할 입력 표면이 **없었다**.
-- 두 증상이 섞여 있다:
--   1) 매일 09:00 시작이 이르다 — 취향 문제. day_start_at 으로 전체 여행에 한 번 말한다.
--   2) 첫날은 비행기·KTX 도착 뒤에야 시작할 수 있다 — **사실 오류**다. 도착 전 시간에 일정이 깔린다.
--      마지막날 출발 시각도 같다(체크아웃·귀가 전까지만).
--
-- **여행 속성으로 둔다**(생성 요청 옵션이 아니라). 도착 시각은 그 여행의 사실이라 재생성해도
-- 유지돼야 하고, 요청 옵션으로 두면 "재생성했더니 9시로 돌아갔다"가 된다.
--
-- 전부 NULL 허용 = 미설정. 기존 여행은 NULL 이라 종전 상수 그대로 돈다(백필 없음).
-- 하루 **끝** 시각(day_end_at)은 이번 범위가 아니다 — 들어온 요구는 시작 쪽이다.
ALTER TABLE trip
  ADD COLUMN day_start_at       time,  -- 하루 일과 시작(전 일자 공통). NULL = 09:00
  ADD COLUMN first_day_start_at time,  -- 첫날만 다른 시작(도착 후). NULL = day_start_at
  ADD COLUMN last_day_end_at    time;  -- 마지막날만 다른 종료(출발 전). NULL = 21:00

-- **당일치기에서만** 첫날 시작과 마지막날 종료가 같은 날에 놓인다 — 그때는 앞뒤가 맞아야 한다.
-- 어긋난 창은 조립기에 모순 입력이 되어 그 날이 통째로 "해 없음"이 되는데, 증상은 "AI 가 일정을
-- 못 만든다"로만 보여 원인이 안 보인다. 애플리케이션에서도 막지만 DB 가 마지막 그물이다.
--
-- 다일 여행은 **두 값이 서로 다른 날에 있어** 비교 자체가 성립하지 않는다(여기서 비교하면
-- "첫날 10시 출발 · 마지막날 09시 귀가"라는 정상 입력을 막는다). 기본 창(09:00~21:00)과의
-- 대소는 코드 상수라 DB 가 알 수 없다 — 그쪽은 애플리케이션이 판정한다.
ALTER TABLE trip
  ADD CONSTRAINT chk_trip_same_day_window
    CHECK (
      start_date <> end_date
      OR first_day_start_at IS NULL
      OR last_day_end_at IS NULL
      OR first_day_start_at < last_day_end_at
    );
