-- TRIP-359 — POI 를 행정구역 표준코드에 붙인다.
-- 번호 근거: V2.24(카탈로그)가 아직 미머지지만 같은 스택의 앞 커밋이라 확정 소비. 열린 PR 중
-- 마이그레이션을 쓰는 다른 건은 없다(2026-08-19 gh 실측).
--
-- 왜 코드인가: poi.region 은 자유 문자열이라 '제주'·'제주도'·'제주특별자치도' 가 다 다른 값이고,
-- 시군구 이름만으로는 '동구' 가 6개 시도에 걸쳐 서로 다른 곳이다(수집분 실측 118건).
-- 지역 커버리지를 셀 수 있으려면 셀 수 있는 키가 있어야 한다.

ALTER TABLE poi ADD COLUMN region_code varchar(5)
  REFERENCES region(region_code);

-- FK 가 "카탈로그에 없는 코드는 저장되지 않는다"를 DB 에서 집행한다. 앱 검증만 두면 다른 경로로
-- 들어온 값이 조용히 남고, 그 뒤 커버리지 집계가 어느 지역에도 안 붙는 유령 코드를 센다.

-- 커버리지 조회는 ACTIVE 만 센다(INV-U1-01) — 그 조건을 인덱스에도 넣는다.
CREATE INDEX ix_poi_region_active ON poi (region_code) WHERE data_status = 'ACTIVE';

-- ── region.poi_count 를 **저장하지 않기로 한다** ─────────────────────────────
-- V2.24 에서 이 칸을 만들었으나, 채우는 쪽을 구현하며 저장이 틀렸음이 드러났다.
-- 값은 POI 가 늘거나 상태가 바뀔 때마다 다시 계산돼야 하는데, 쓰기 경로를 하나만 빠뜨려도
-- 아무도 실패하지 않는다 — 화면은 커버리지가 있는 지역을 "준비 중"으로 계속 그린다.
-- 조회 시점 집계는 항상 맞고, 카탈로그가 300행이라 비용도 문제가 되지 않는다.
ALTER TABLE region DROP COLUMN poi_count;
