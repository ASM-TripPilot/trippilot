package com.trippilot.placedata.api

/**
 * 목적지 수용 판정 퍼사드(C7 · TRIP-360) — 여행 생성이 목적지를 받을지 정할 때 쓴다(INV-U1-12).
 *
 * **판정의 기준은 행정구역 카탈로그다.** 이전에는 카카오 지오코딩이 기준이었는데, 그러면
 * 벤더 쿼터·장애가 곧 여행 생성 실패율이 되고, 좌표가 잡힌다는 것이 "우리가 지원하는 목적지"를
 * 뜻하지도 않는다(`성산일출봉` 도 좌표는 잡힌다). 카탈로그는 국내만 담으므로 국내강제는 자동 성립하고,
 * 외부 호출 없이 판정이 끝난다.
 *
 * 지오코딩은 **거절 사유를 가르는 데만** 쓴다 — 통과 경로에는 외부 호출이 없다.
 */
interface DestinationFacade {
    /** 이 지역명을 목적지로 받을 수 있는가. */
    fun check(region: String): DestinationCheck
}

/**
 * 판정 결과. **[SUPPORTED] 외에는 전부 거절**이고, 나머지 셋은 사용자에게 다른 말을 하기 위해 갈라 둔다.
 *
 * 같은 문구로 뭉치면 사용자는 자기가 무엇을 고쳐야 하는지 모른다 — `홍천읍` 을 넣은 사람에게
 * "국내 여행만 지원해요" 라고 답하면 거짓이고, 무엇을 해야 하는지도 알려주지 못한다(INV-4).
 */
enum class DestinationCheck {
    /** 카탈로그에 이름 또는 별칭으로 있다. */
    SUPPORTED,

    /** 국내인 것은 확인됐으나 카탈로그에 없다 — 읍·면·동이나 명소명일 때. 시·군·구로 고르게 안내한다. */
    DOMESTIC_UNSUPPORTED,

    /** 국외. */
    OUTSIDE,

    /**
     * 카탈로그에 없고 외부 확인도 못 했다.
     *
     * **이 경우도 거절한다.** 예전 규칙은 "확인 못 한 것은 막지 않는다" 였는데, 그건 지오코딩이
     * 유일한 기준이라 벤더 장애가 곧 전면 차단이었기 때문이다. 이제 정상 목적지는 카탈로그에서
     * 끝나 외부를 타지 않으므로, 여기까지 온 값은 **어차피 우리가 지원하지 않는 이름**이다.
     */
    UNVERIFIED,
}
