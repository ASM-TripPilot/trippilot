package com.trippilot.notification.domain

/**
 * 푸시 전달 긴급도 — 종류별로 OS 에 다른 신호를 준다([NotificationKind.urgency]).
 *
 * **통제권은 사용자에게 남는다.** iOS 는 집중 모드 설정에서 앱별로 시간 민감 알림을 끌 수 있고,
 * Android 는 채널별로 방해금지 우회를 끌 수 있다. 서버가 전면 차단하는 것과 다르다 —
 * 우리는 "이게 급한가"를 말할 뿐이고 "받을 것인가"는 사용자가 정한다.
 *
 * `critical`(경보음 강제)은 두지 않는다 — 애플의 별도 엔타이틀먼트가 필요하고, 여행 일정 알림이
 * 재난 경보와 같은 등급을 요구할 근거가 없다.
 */
enum class PushUrgency {
    /** 조용히 쌓인다. 알림 요약에 묶여도 좋다. */
    PASSIVE,

    /** 보통. 기본 동작을 따른다. */
    ACTIVE,

    /**
     * 집중 모드를 뚫는다. **시각이 곧 내용인 알림에만** 쓴다 —
     * 남발하면 사용자가 앱 단위로 이 권한을 꺼 버려 정작 필요할 때 못 뚫는다.
     */
    TIME_SENSITIVE,
}
